import pathlib
import re
import tempfile
import unittest

import pystencils as ps
from pystencils.types import PsPointerType
from pystencilssfg.exceptions import SfgException
from pystencilssfg.lang import AugExpr

import accessor_catalogue as cat
import accessor_sfg
import sfg_driver

DOUBLE = ps.create_type("float64")


def squash(text):
    """Text without whitespace: independent of clang-format."""
    return re.sub(r"\s+", "", text)


def generate(body, header_only=True, target="cpu"):
    """Files generated by ``body(sfg)``, by name."""
    ctx = sfg_driver.CodegenContext("double", target)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        with sfg_driver.KernelFileGenerator(
                "Foo", ctx, tmp, "test.py", header_only=header_only) as sfg:
            body(sfg)
        return {p.name: p.read_text() for p in tmp.iterdir()}


class FunctionTest(unittest.TestCase):

    def test_overloads_are_allowed(self):
        def body(sfg):
            x, w = sfg.var("x", DOUBLE), sfg.var("w", DOUBLE)
            accessor_sfg.function(sfg, "get", x, returns=DOUBLE,
                                  inline=True)("return x;")
            accessor_sfg.function(sfg, "get", x, w, returns=DOUBLE,
                                  inline=True)("return w;")
        header = squash(generate(body)["Foo.h"])
        self.assertIn("inlinedoubleget(doublex)", header)
        self.assertIn("inlinedoubleget(doublex,doublew)", header)

    def test_stock_composer_rejects_overloads(self):
        # if pystencils-sfg supports overloads, accessor_sfg.AllowOverloads
        # is obsolete
        def body(sfg):
            sfg.function("get")("return 1;")
            sfg.function("get")("return 2;")
        with self.assertRaises(ValueError):
            generate(body)

    def test_functions_are_declared_unless_inline(self):
        def body(sfg):
            accessor_sfg.function(sfg, "get", sfg.var("x", DOUBLE),
                                  returns=DOUBLE)("return x;")
        files = generate(body, header_only=False)
        self.assertIn("doubleget(doublex);", squash(files["Foo.h"]))
        self.assertNotIn("inline", files["Foo.h"])
        self.assertIn("doubleget(doublex){returnx;}", squash(files["Foo.cpp"]))

    def test_function_without_return_type_is_void(self):
        def body(sfg):
            accessor_sfg.function(sfg, "set", sfg.var("x", DOUBLE),
                                  inline=True)("x;")
        self.assertIn("inlinevoidset(doublex)",
                      squash(generate(body)["Foo.h"]))


class StatementTest(unittest.TestCase):

    def test_definitions_and_uses(self):
        def body(sfg):
            x = sfg.var("x", DOUBLE)
            y = AugExpr(DOUBLE).var("y")
            z = AugExpr(DOUBLE).var("z")
            accessor_sfg.function(sfg, "get", x, returns=DOUBLE,
                                  inline=True)(
                accessor_sfg.statement("double y = x;", (y,), (x,)),
                accessor_sfg.statement("double z = y;", (z,), (y,)),
                "return z;")
        header = squash(generate(body)["Foo.h"])
        self.assertIn("doubley=x;doublez=y;returnz;", header)

    def test_used_variables_must_be_parameters(self):
        def body(sfg):
            y = AugExpr(DOUBLE).var("y")
            accessor_sfg.function(sfg, "get", sfg.var("x", DOUBLE))(
                accessor_sfg.statement("double q = y;", (), (y,)))
        with self.assertRaises(SfgException):
            generate(body)


class LinearBufferTest(unittest.TestCase):

    @staticmethod
    def buffer(sizes, fsize):
        return accessor_sfg.LinearBuffer(
            PsPointerType(DOUBLE), [AugExpr.format(s) for s in sizes],
            fsize).var("p")

    def test_extents(self):
        buffer = self.buffer(["n", "m"], 3)
        self.assertEqual([str(buffer._extract_size(i)) for i in range(3)],
                         ["n", "m", "3"])
        self.assertEqual(str(buffer._extract_ptr()), "p")

    def test_first_coordinate_is_slowest_and_values_are_fastest(self):
        buffer = self.buffer(["n", "m", "l"], 19)
        self.assertEqual([str(buffer._extract_stride(i)) for i in range(4)],
                         ["19 * m * l", "19 * l", "19", "1"])

    def test_rank_one(self):
        buffer = self.buffer(["n"], 3)
        self.assertEqual([str(buffer._extract_stride(i)) for i in range(2)],
                         ["3", "1"])


class KernelParamTest(unittest.TestCase):

    def test_scalar_parameters(self):
        found = {}

        def body(sfg):
            field = ps.Field.create_generic("f", 3, DOUBLE)
            density = ps.TypedSymbol("density", DOUBLE)
            kernel = sfg.kernels.create(
                [ps.Assignment(field.center, density)], "scale",
                ps.CreateKernelConfig(default_dtype=DOUBLE))
            found["density"] = accessor_sfg.kernel_param(kernel, "density")
            found["other"] = accessor_sfg.kernel_param(kernel, "other")
        generate(body)
        self.assertEqual(found["density"].name, "density")
        self.assertIsNone(found["other"])


class ContainerTest(unittest.TestCase):
    """C++ spelling of the containers of the catalogue."""

    CONTAINERS = {
        "scalar": cat.SCALAR, "array": cat.array(19), "vector3": cat.VECTOR3,
        "matrix3": cat.MATRIX3, "std_vector": cat.STD_VECTOR}

    def test_number_of_values_per_cell(self):
        self.assertEqual(accessor_sfg.n_cells(1), "ci.numCells()")
        self.assertEqual(accessor_sfg.n_cells(19), "ci.numCells() * 19u")

    def test_types(self):
        T = "double"
        self.assertEqual(
            {k: accessor_sfg.cxx_type(c, T)
             for k, c in self.CONTAINERS.items()},
            {"scalar": "double", "array": "std::array<double, 19u>",
             "vector3": "walberla::Vector3<double>",
             "matrix3": "walberla::Matrix3<double>",
             "std_vector": "std::vector<double>"})

    def test_local_declarations(self):
        declare = accessor_sfg.local_declaration
        T = "float"
        self.assertEqual(declare(cat.SCALAR, T, "rho"), "float rho{};")
        self.assertEqual(declare(cat.array(19), T, "pop"),
                         "std::array<float, 19u> pop;")
        self.assertEqual(declare(cat.VECTOR3, T, "vec"),
                         "walberla::Vector3<float> vec;")
        self.assertEqual(declare(cat.MATRIX3, T, "out"),
                         "walberla::Matrix3<float> out;")
        self.assertEqual(declare(cat.STD_VECTOR, T, "out", 1),
                         "std::vector<float> out(ci.numCells());")
        self.assertEqual(declare(cat.STD_VECTOR, T, "out", 3),
                         "std::vector<float> out(ci.numCells() * 3u);")

    def test_data_pointers(self):
        self.assertEqual(accessor_sfg.data_pointer(cat.SCALAR, "rho"),
                         "&rho")
        for container in (cat.array(19), cat.VECTOR3, cat.STD_VECTOR):
            self.assertEqual(accessor_sfg.data_pointer(container, "x"),
                             "x.data()")

    def test_construction(self):
        self.assertEqual(
            accessor_sfg.construction(cat.VECTOR3, "double", ["a", "b", "c"]),
            "walberla::Vector3<double>(a, b, c)")
        self.assertEqual(
            accessor_sfg.construction(cat.MATRIX3, "float", ["a"] * 2),
            "walberla::Matrix3<float>(a, a)")
        with self.assertRaises(AssertionError):
            accessor_sfg.construction(cat.SCALAR, "float", ["a"])

    def test_parameters_are_const_references(self):
        def body(sfg):
            params = [accessor_sfg.value_var(c, DOUBLE, f"x{i}")
                      for i, c in enumerate(
                          (cat.array(19), cat.VECTOR3, cat.STD_VECTOR))]
            accessor_sfg.function(sfg, "get", *params, inline=True)("x0;")
        header = squash(generate(body)["Foo.h"])
        self.assertIn(squash(
            "inline void get(const std::array<double, 19u> &x0, "
            "const walberla::Vector3<double> &x1, "
            "const std::vector<double> &x2)"), header)
        with self.assertRaises(ValueError):
            accessor_sfg.value_var(cat.SCALAR, DOUBLE, "x")

    def test_return_types(self):
        def body(sfg):
            for i, container in enumerate(self.CONTAINERS.values()):
                accessor_sfg.function(
                    sfg, f"get{i}", returns=accessor_sfg.return_type(
                        container, DOUBLE), inline=True)("x;")
        header = squash(generate(body)["Foo.h"])
        for expected in ("inline double get0()",
                         "inline std::array<double, 19u> get1()",
                         "inline walberla::Vector3<double> get2()",
                         "inline walberla::Matrix3<double> get3()",
                         "inline std::vector<double> get4()"):
            self.assertIn(squash(expected), header)


if __name__ == "__main__":
    unittest.main()
