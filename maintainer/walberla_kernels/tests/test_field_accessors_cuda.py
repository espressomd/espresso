import pathlib
import re
import tempfile
import unittest

import field_accessors_cuda
import generate_lb_kernels
import pystencils_espresso
import sfg_driver
from tests import header_api

# The API data files were extracted from the CUDA FieldAccessors headers
# generated with pystencils 1.4 (Jinja template), without the declarations of
# the namespaces DensityAndVelocity and DensityAndMomentumDensity, which
# were never defined. They are the API contract of the waLBerla bridge, which
# the generated accessors must fulfill.
DATA_DIR = pathlib.Path(__file__).resolve().parent / "data"
NAMESPACES = ("Population", "Vector", "Interpolation", "Density", "Velocity",
              "Force", "MomentumDensity", "PressureTensor")


def generate_files():
    tmp = pathlib.Path(tempfile.mkdtemp())
    for precision in ("double", "single"):
        ctx = sfg_driver.CodegenContext(precision, "cuda")
        fields = pystencils_espresso.generate_fields(
            generate_lb_kernels.STENCIL, ctx.data_type)
        method = generate_lb_kernels.create_lb_method(fields)
        with sfg_driver.KernelFileGenerator(
                ctx.class_name("FieldAccessors"), ctx, tmp,
                "generate_lb_kernels.py", header_extension="cuh") as sfg:
            field_accessors_cuda.generate_field_accessors_cuda(
                sfg, ctx, method)
    return tmp


def namespace_block(source, name):
    """Text of all blocks of the namespace ``name`` of a source file."""
    blocks = re.findall(rf"^\s*namespace {name} \{{.*?^\s*\}} // namespace "
                        rf"{name}$", source, re.S | re.M)
    assert blocks, name
    return "\n".join(blocks)


def remove_directory(path):
    for item in path.iterdir():
        item.unlink()
    path.rmdir()


class FieldAccessorsCudaTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.tmp = generate_files()
        cls.headers = {
            p: (cls.tmp / f"FieldAccessors{p}PrecisionCUDA.cuh").read_text()
            for p in ("Double", "Single")}
        cls.sources = {
            p: (cls.tmp / f"FieldAccessors{p}PrecisionCUDA.cu").read_text()
            for p in ("Double", "Single")}

    @classmethod
    def tearDownClass(cls):
        remove_directory(cls.tmp)

    def test_files_are_generated(self):
        self.assertEqual(
            sorted(p.name for p in self.tmp.iterdir()),
            ["FieldAccessorsDoublePrecisionCUDA.cu",
             "FieldAccessorsDoublePrecisionCUDA.cuh",
             "FieldAccessorsSinglePrecisionCUDA.cu",
             "FieldAccessorsSinglePrecisionCUDA.cuh"])

    def test_metadata(self):
        for precision in ("Double", "Single"):
            header = self.headers[precision]
            self.assertIn(
                "Generated by maintainer/walberla_kernels/"
                "generate_lb_kernels.py", header)
            self.assertIn("thrust/device_vector.h", header)
            self.assertIn("gpu/GPUField.h", header)
            self.assertIn(
                f"#include \"FieldAccessors{precision}PrecisionCUDA.cuh\"",
                self.sources[precision])

    def test_namespaces_of_functions(self):
        for header in self.headers.values():
            namespaces = {
                f[0] for f in header_api.functions(header, declarations=True)}
            self.assertEqual(
                namespaces, {f"lbm::accessor::{n}" for n in NAMESPACES})

    def test_single_precision_has_no_double(self):
        for text in (self.headers["Single"], self.sources["Single"]):
            self.assertNotIn("double", text)
            self.assertIn("float", text)

    def test_double_precision_has_no_float(self):
        for text in (self.headers["Double"], self.sources["Double"]):
            self.assertIsNone(re.search(r"\bfloat\b|\d\.\d*f\b", text))

    def test_functions_are_declared_not_defined(self):
        for header in self.headers.values():
            self.assertEqual(header_api.functions(header), [])
            self.assertEqual(len(header_api.functions(
                header, declarations=True)), 32)

    def test_functions_are_defined(self):
        # every declared function is defined in the source file, in the
        # same namespace
        for precision, header in self.headers.items():
            for namespace, name, _, _ in header_api.functions(
                    header, declarations=True):
                block = re.sub(
                    r"namespace kernels \{.*?\} // namespace kernels", "",
                    namespace_block(self.sources[precision],
                                    namespace.split("::")[-1]),
                    flags=re.S)
                self.assertRegex(block, re.compile(
                    rf"^[\w:<>,\s]*\b{name}\(", re.M))

    def test_api_equals_frozen_contract(self):
        for precision, header in self.headers.items():
            reference = header_api.load_records(
                DATA_DIR / f"field_accessors_cuda_api_{precision.lower()}.json")
            expected = header_api.counters(reference)
            actual = header_api.signature_counters(header, declarations=True)
            self.assertEqual(sum(expected["return type"].values()), 32)
            for label, counter in expected.items():
                self.assertEqual(
                    actual[label], counter,
                    f"{precision} precision, {label}: "
                    f"missing {counter - actual[label]}, "
                    f"unexpected {actual[label] - counter}")

    def test_kernels_are_generated_by_pystencils(self):
        for source in self.sources.values():
            self.assertGreaterEqual(source.count("__global__"), 20)
            self.assertNotIn("make_kernel", source)
            self.assertIn("pystencils_runtime/cuda.cuh", source)

    def test_atomics_only_scatter_forces(self):
        for precision, source in self.sources.items():
            self.assertEqual(source.count("atomicAdd"), 1)
            self.assertIn("atomicAdd", namespace_block(
                source, "Interpolation"))
            for name in ("MomentumDensity", "PressureTensor"):
                block = namespace_block(source, name)
                self.assertNotIn("atomic", block, (precision, name))
                self.assertNotIn("__shfl", block, (precision, name))

    def test_reductions_sum_in_cell_order_on_the_host(self):
        for source in self.sources.values():
            for name, n in (("MomentumDensity", 3), ("PressureTensor", 9)):
                block = namespace_block(source, name)
                self.assertIn(
                    f"for (auto i = uint_t{{0u}}; i < out.size(); "
                    f"i += {n}u)", block)
                self.assertEqual(
                    len(re.findall(r"\+= out\[i \+ \d+u\];", block)), n)

    def test_floor_matches_the_precision(self):
        # the legacy double precision kernels called floorf()
        self.assertIsNone(re.search(r"\bfloorf\(", self.sources["Double"]))
        self.assertRegex(self.sources["Double"], r"\bfloor\(")
        self.assertRegex(self.sources["Single"], r"\bfloorf\(")

    def test_velocity_interval_buffer_has_all_cells(self):
        # the legacy function allocated the buffer of a single cell
        for precision, source in self.sources.items():
            block = namespace_block(source, "Velocity")
            fp = "double" if precision == "Double" else "float"
            function = re.search(
                rf"std::vector<\s*{fp}\s*>\s+get\([^)]*CellInterval[^)]*\)"
                rf"\s*\{{(.*?return out;)", block, re.S)
            self.assertIsNotNone(function)
            self.assertIn("dev_data(ci.numCells() * 3u)", function.group(1))
            self.assertIn(f"std::vector<{fp}> out(ci.numCells() * 3u);",
                          function.group(1))
            self.assertNotIn("dev_data(3u)", function.group(1))

    def test_generation_is_deterministic(self):
        second = generate_files()
        self.addCleanup(remove_directory, second)
        for path in sorted(self.tmp.iterdir()):
            self.assertEqual(path.read_text(),
                             (second / path.name).read_text(), path.name)


if __name__ == "__main__":
    unittest.main()
