class CodegenContextTest(unittest.TestCase):

    def test_class_name(self):
        def name(precision, target):
            ctx = sfg_driver.CodegenContext(precision, target)
            return ctx.class_name("InitialPDFsSetter")
        self.assertEqual(name("double", "cpu"),
                         "InitialPDFsSetterDoublePrecision")
        self.assertEqual(name("single", "avx"),
                         "InitialPDFsSetterSinglePrecisionAVX")
        self.assertEqual(name("single", "cuda"),
                         "InitialPDFsSetterSinglePrecisionCUDA")

    def test_invalid_arguments(self):
        with self.assertRaises(AssertionError):
            sfg_driver.CodegenContext("half", "cpu")
        with self.assertRaises(AssertionError):
            sfg_driver.CodegenContext("double", "hip")

    def test_data_type(self):
        self.assertEqual(sfg_driver.CodegenContext("double", "cpu").data_type,
                         ps.create_type("float64"))
        self.assertEqual(sfg_driver.CodegenContext("single", "cpu").data_type,
                         ps.create_type("float32"))

    def test_build_config(self):
        cpu = sfg_driver.CodegenContext("double", "cpu").build_config()
        self.assertTrue(cpu.use_double_precision)
        self.assertTrue(cpu.openmp_enabled)
        self.assertFalse(cpu.cuda_enabled)
        self.assertEqual(cpu.target, ps.Target.GenericCPU)
        avx = sfg_driver.CodegenContext("single", "avx").build_config()
        self.assertFalse(avx.use_double_precision)
        self.assertEqual(avx.target, ps.Target.X86_AVX)
        cuda = sfg_driver.CodegenContext("double", "cuda").build_config()
        self.assertTrue(cuda.cuda_enabled)
        self.assertFalse(cuda.openmp_enabled)
        self.assertEqual(cuda.target, ps.Target.CUDA)


class KernelFileGeneratorTest(unittest.TestCase):

    def generate(self, target):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", target)
        with sfg_driver.KernelFileGenerator("Foo", ctx, tmp, "test.py") as sfg:
            sfg.code("int foo();")
        return tmp

    def test_cpu_file_names_and_metadata(self):
        tmp = self.generate("cpu")
        self.assertEqual(sorted(p.name for p in tmp.iterdir()),
                         ["Foo.cpp", "Foo.h"])
        header = (tmp / "Foo.h").read_text()
        self.assertIn(
            "Generated by maintainer/walberla_kernels/test.py", header)
        self.assertIn(f"pystencils v{ps.__version__}", header)
        self.assertIn("int foo();", header)

    def test_cuda_file_names(self):
        tmp = self.generate("cuda")
        self.assertEqual(sorted(p.name for p in tmp.iterdir()),
                         ["Foo.cu", "Foo.h"])

    def test_header_extension(self):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", "cuda")
        with sfg_driver.KernelFileGenerator(
                "Foo", ctx, tmp, "test.py", header_extension="cuh") as sfg:
            sfg.function("foo")("return;")
        self.assertEqual(sorted(p.name for p in tmp.iterdir()),
                         ["Foo.cu", "Foo.cuh"])
        self.assertIn('#include "Foo.cuh"', (tmp / "Foo.cu").read_text())

    def test_header_only(self):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", "cpu")
        with sfg_driver.KernelFileGenerator(
                "Foo", ctx, tmp, "test.py", header_only=True) as sfg:
            sfg.function("foo").returns("int")("return 1;")
        self.assertEqual([p.name for p in tmp.iterdir()], ["Foo.h"])
        header = (tmp / "Foo.h").read_text()
        self.assertRegex(header, r"inline \S+ foo\(\)")
        self.assertIn("return 1;", header)

    def test_clang_format_is_not_run(self):
        # pystencils-sfg formats its output if it finds clang-format on PATH:
        # the generated files must not depend on it, they are formatted
        # afterwards with the formatting script of the repository
        bin_dir = pathlib.Path(self.enterContext(
            tempfile.TemporaryDirectory()))
        marker = bin_dir / "called"
        script = bin_dir / "clang-format"
        script.write_text(f"#!/bin/sh\ntouch {marker}\ncat\n")
        script.chmod(script.stat().st_mode | stat.S_IEXEC)
        path = f"{bin_dir}{os.pathsep}{os.environ['PATH']}"
        with unittest.mock.patch.dict(os.environ, {"PATH": path}):
            tmp = self.generate("cpu")
        self.assertTrue((tmp / "Foo.h").is_file())
        self.assertFalse(marker.exists())


class ToolchainCheckTest(unittest.TestCase):

    CMAKE = """
FetchContent_Declare(
  zlib
  GIT_TAG 1111111111111111111111111111111111111111
)
FetchContent_Declare(
  walberla
  GIT_REPOSITORY https://example.org/walberla.git
  GIT_TAG        0123456789abcdef0123456789abcdef01234567 # some/branch
  SYSTEM
)
"""

    def test_installed_toolchain_passes_silently(self):
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            sfg_driver.check_toolchain()
        self.assertEqual([str(w.message) for w in caught], [])

    def test_old_version_is_an_error(self):
        with unittest.mock.patch.object(ps, "__version__", "2.0.9"):
            errors = sfg_driver.check_versions()
        self.assertEqual(len(errors), 1)
        self.assertIn("pystencils", errors[0])
        self.assertIn("2.0.9", errors[0])
        with unittest.mock.patch.object(ps, "__version__", "2.0.9"):
            with self.assertRaisesRegex(RuntimeError, "pystencils"):
                sfg_driver.check_toolchain()

    def test_untested_version_only_warns(self):
        with unittest.mock.patch.object(lbmpy, "__version__", "2.2.0"):
            with self.assertWarns(UserWarning) as cm:
                errors = sfg_driver.check_versions()
        self.assertEqual(errors, [])
        message = str(cm.warning)
        self.assertNotIn("\n", message)
        for text in ("lbmpy", "2.2.0", "2.1.1"):
            self.assertIn(text, message)

    def test_equivalent_version_spelling_is_tested(self):
        # pystencils 2.1 is the tested 2.1.0
        with unittest.mock.patch.object(ps, "__version__", "2.1"):
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                self.assertEqual(sfg_driver.check_versions(), [])
        self.assertEqual(caught, [])

    def test_feature_probe(self):
        self.assertEqual(sfg_driver.missing_features(), [])
        table = (*sfg_driver.REQUIRED_FEATURES,
                 "pystencils.fd.no_such_function",
                 "sweepgen.api.NoSuchClass._extract_size",
                 "no_such_package.thing")
        missing = sfg_driver.missing_features(table)
        self.assertEqual(missing, list(table[-3:]))
        with unittest.mock.patch.object(
                sfg_driver, "REQUIRED_FEATURES", table):
            with self.assertRaises(RuntimeError) as cm:
                sfg_driver.check_toolchain()
        for name in table[-3:]:
            self.assertIn(name, str(cm.exception))

    def test_feature_table_is_unique_dotted_paths(self):
        table = sfg_driver.REQUIRED_FEATURES
        self.assertGreater(len(table), 50)
        self.assertEqual(len(set(table)), len(table))
        for name in table:
            self.assertRegex(name, r"^\w+(\.\w+)+$")

    def test_walberla_commit_of_sample(self):
        self.assertEqual(sfg_driver.walberla_commit(self.CMAKE),
                         "0123456789abcdef0123456789abcdef01234567")
        with self.assertRaisesRegex(RuntimeError, "GIT_TAG"):
            sfg_driver.walberla_commit("FetchContent_Declare(zlib)")

    def test_walberla_commit_of_cmakelists(self):
        commit = sfg_driver.walberla_commit()
        self.assertRegex(commit, "^[0-9a-f]{40}$")
        self.assertTrue(commit.startswith(
            sfg_driver.SWEEPGEN_COMMIT_RE.search(sweepgen.__version__)[1]))

    def test_sweepgen_commit_match(self):
        commit = "0123456789abcdef0123456789abcdef01234567"
        self.assertEqual(
            sfg_driver.check_sweepgen_commit("7.3+8.g0123456", commit), [])
        errors = sfg_driver.check_sweepgen_commit("7.3+8.gfedcba9", commit)
        self.assertEqual(len(errors), 1)
        self.assertIn("_deps/walberla-src/sweepgen", errors[0])
        self.assertIn("fedcba9", errors[0])
        self.assertIn("0123456", errors[0])
        errors = sfg_driver.check_sweepgen_commit("7.3", commit)
        self.assertEqual(len(errors), 1)


class GenerateSweepTest(unittest.TestCase):

    def generate(self, target, swap=False, rng_parameters=False):
        """Header of a toy sweep ``Toy`` (a stream step if ``swap``)."""
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", target)
        f, f_tmp = ps.fields(f"f, f_tmp: {ctx.data_type.c_string()}[3D]",
                             layout="fzyx")
        rhs = sp.Symbol("alpha") * f[1, 0, 0]
        if rng_parameters:
            ints = [ps.TypedSymbol(name, DynamicType.INDEX_TYPE) for name in (
                "block_offset_0", "block_offset_1", "block_offset_2", "seed",
                "time_step")]
            rhs = rhs + tcast(sum(ints), ctx.data_type)
        assignments = [ps.Assignment(f_tmp.center, rhs)]
        with sfg_driver.KernelFileGenerator(
                "Toy", ctx, tmp, "test.py") as sfg:
            sfg_driver.generate_sweep(
                sfg, "Toy", assignments,
                swap_fields=[(f, f_tmp)] if swap else ())
        return (tmp / "Toy.h").read_text()

    def test_plain_sweepgen_class(self):
        header = self.generate("cpu")
        self.assertIn("namespace walberla::pystencils {", header)
        self.assertEqual(header.count("class Toy {"), 1)
        self.assertNotIn("internal", header)
        self.assertNotIn("impl_", header)
        # the constructor takes all the properties, the accessors return
        # references
        self.assertIn("Toy (walberla::BlockDataID fId, "
                      "walberla::BlockDataID f_tmpId, double alpha)", header)
        self.assertIn("double& alpha()", header)
        self.assertIn("const double& alpha() const", header)
        self.assertIn("void operator()(walberla::IBlock * block)", header)
        self.assertIn("void runOnCellInterval(walberla::IBlock * block, "
                      "const walberla::CellInterval& ci)", header)
        self.assertNotIn("swapShadowBuffers", header)

    def test_cuda_execution_tag(self):
        header = self.generate("cuda")
        self.assertIn("walberla::v8::sweep::exectag::GPU exTag", header)
        self.assertNotIn("gpuStream_t stream", header)

    def test_swapped_fields_are_hidden(self):
        header = self.generate("cpu", swap=True)
        self.assertIn("Toy (walberla::BlockDataID fId, double alpha)", header)
        self.assertIn("swapShadowBuffers(", header)
        self.assertNotIn("f_tmpId", header)

    def test_block_offset_is_one_property(self):
        # the RNG offsets of the kernel are combined into a Vector3 that is
        # set by the caller (per block)
        header = self.generate("cpu", swap=True, rng_parameters=True)
        self.assertIn(
            "Toy (walberla::BlockDataID fId, double alpha, "
            "walberla::Vector3< int64_t > block_offset, int64_t seed, "
            "int64_t time_step)", header)
        self.assertIn("walberla::Vector3< int64_t >& block_offset()", header)
        self.assertNotIn("block_offset_0", header)


class GenerateMainTest(unittest.TestCase):

    @staticmethod
    def kernels():
        def generate(sfg, ctx, name):
            sfg.code(f"// {name}")
        return {
            "foo": sfg_driver.Kernel("Foo", ("cpu", "cuda"), generate),
            "bar": sfg_driver.Kernel("Bar", ("cpu",), generate,
                                     header_only=True),
        }

    def run_main(self, *args):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            sfg_driver.generate_main(
                "Generate toys.", "toy.py", self.kernels(),
                ["--output-dir", str(tmp), *args])
        return sorted(p.name for p in tmp.iterdir()), output.getvalue()

    def test_all_kernels_are_the_default(self):
        files, output = self.run_main()
        self.assertEqual(files, [
            f"{stem}{precision}Precision{target}.{extension}"
            for stem, targets in (
                ("Bar", [("", ("h",))]),
                ("Foo", [("", ("cpp", "h")), ("CUDA", ("cu", "h"))]))
            for precision in ("Double", "Single")
            for target, extensions in targets for extension in extensions
        ])
        self.assertIn("generated FooSinglePrecisionCUDA", output)
        self.assertIn("skipping bar for target cuda: not supported", output)
        # the AVX target exists for neither toy kernel
        self.assertEqual(output.count("skipping"), 6)

    def test_selection(self):
        files, output = self.run_main(
            "--kernels", "foo", "foo", "--precision", "double", "--target",
            "cuda")
        self.assertEqual(files, ["FooDoublePrecisionCUDA.cu",
                                 "FooDoublePrecisionCUDA.h"])
        self.assertEqual(output, "generated FooDoublePrecisionCUDA\n")

    def test_header_only_kernel_has_no_source(self):
        files, _ = self.run_main("--kernels", "bar", "--target", "cpu")
        self.assertEqual(files, ["BarDoublePrecision.h",
                                 "BarSinglePrecision.h"])

    def test_unknown_kernel_is_rejected(self):
        with contextlib.redirect_stderr(io.StringIO()):
            with self.assertRaises(SystemExit):
                self.run_main("--kernels", "baz")

    def test_expand(self):
        self.assertEqual(sfg_driver.expand(["all"], ("a", "b")), ["a", "b"])
        self.assertEqual(sfg_driver.expand(["b", "a", "b"], ("a", "b")),
                         ["b", "a"])


class GenerateSparseSweepTest(unittest.TestCase):

    def generate(self, target, **kwargs):
        """Files of a toy sparse sweep ``Toy`` that increments a field in the
        cells of its index list."""
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", target)
        f = ps.Field.create_generic(
            "f", 3, ctx.data_type, index_dimensions=0, layout="fzyx",
            field_type=ps.FieldType.CUSTOM)
        index_list = sfg_driver.index_list_field()
        cell = tuple(index_list[0](c) for c in "xyz")
        target_cell = f.absolute_access(cell, ())
        assignments = [ps.Assignment(
            target_cell, target_cell + sp.Symbol("alpha"))]
        with sfg_driver.KernelFileGenerator(
                "Toy", ctx, tmp, "test.py") as sfg:
            sfg_driver.generate_sweep(
                sfg, "Toy", assignments, **{"sparse": True, **kwargs})
        return {p.name: p.read_text() for p in tmp.iterdir()}

    def test_index_list_field(self):
        field = sfg_driver.index_list_field()
        self.assertEqual(field.name, "indexList")
        self.assertEqual(field.field_type, ps.FieldType.INDEXED)
        self.assertEqual(field.dtype.name, "walberla::v8::sweep::CellIdx")
        self.assertEqual([m.name for m in field.dtype.members],
                         ["x", "y", "z"])

    def test_constructor_takes_the_index_list(self):
        header = self.generate("cpu")["Toy.h"]
        self.assertEqual(header.count("class Toy {"), 1)
        self.assertIn("walberla::v8::sweep::SparseIndexList", header)
        self.assertRegex(
            header, r"Toy \(walberla::BlockDataID fId, "
            r"walberla::v8::sweep::SparseIndexList< .* > indexList, "
            r"double alpha\)")
        self.assertIn("void operator()(walberla::IBlock * block)", header)
        self.assertNotIn("runOnCellInterval", header)

    def test_cpu_kernel_loops_over_the_index_list(self):
        source = self.generate("cpu")["Toy.cpp"]
        self.assertIn("sparse_idx", source)
        self.assertIn("#pragma omp", source)
        self.assertNotIn("__global__", source)

    def test_cuda_kernel(self):
        files = self.generate("cuda")
        self.assertEqual(sorted(files), ["Toy.cu", "Toy.h"])
        self.assertIn("__global__", files["Toy.cu"])
        self.assertNotIn("runOnCellInterval", files["Toy.h"])

    def test_gen_config_of_the_caller_is_not_modified(self):
        config = ps.CreateKernelConfig()
        self.assertIn("Toy.h", self.generate("cpu", gen_config=config))
        self.assertIsNone(config.index_field)
        self.assertFalse(config.skip_independence_check)

    def test_sparse_configuration_of_the_caller(self):
        # a configuration with an index field makes a sweep sparse, which
        # must be requested explicitly
        config = ps.CreateKernelConfig()
        config.index_field = sfg_driver.index_list_field()
        config.skip_independence_check = True
        with self.assertRaisesRegex(ValueError, "is sparse"):
            self.generate("cpu", gen_config=config, sparse=False)
        self.assertIn("Toy.h", self.generate("cpu", gen_config=config))

    def test_sparse_rejects_conflicting_configuration(self):
        config = ps.CreateKernelConfig()
        config.index_field = ps.Field.create_generic(
            "other", 1, sweepgen.api.CellIdx,
            field_type=ps.FieldType.INDEXED)
        with self.assertRaisesRegex(ValueError, "another index field"):
            self.generate("cpu", gen_config=config)
        config = ps.CreateKernelConfig()
        config.skip_independence_check = False
        with self.assertRaisesRegex(ValueError, "skip_independence_check"):
            self.generate("cpu", gen_config=config)

    def test_dense_sweep_is_not_sparse(self):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", "cpu")
        f, g = ps.fields(f"f, g: {ctx.data_type.c_string()}[3D]")
        with sfg_driver.KernelFileGenerator(
                "Toy", ctx, tmp, "test.py") as sfg:
            sfg_driver.generate_sweep(
                sfg, "Toy", [ps.Assignment(g.center, f.center)])
        header = (tmp / "Toy.h").read_text()
        self.assertNotIn("SparseIndexList", header)
        self.assertIn("runOnCellInterval", header)


class PatchKernelSourceTest(unittest.TestCase):

    def test_rng_namespace_is_global(self):
        source = ("auto r = pystencils::runtime::random::philox_float64(x);\n"
                  "auto s = ::pystencils::runtime::random::philox_float32(y);")
        patched = sfg_driver.patch_kernel_source(source)
        self.assertIn("auto r = ::pystencils::runtime::random::philox_float64",
                      patched)
        self.assertIn("auto s = ::pystencils::runtime::random::philox_float32",
                      patched)
        self.assertNotIn(":::", patched)

    def test_math_functions_are_qualified(self):
        source = ("x = sqrt(2.0f) + fmin(a, fmax(b, c)) + sqrtf(d) "
                  "+ std::sqrt(e);")
        self.assertEqual(
            sfg_driver.patch_kernel_source(source),
            "x = std::sqrt(2.0f) + std::fmin(a, std::fmax(b, c)) + sqrtf(d) "
            "+ std::sqrt(e);")

    def test_pow_is_qualified(self):
        source = ("x = pow(a, 2.0f) + powf(b, c) + std::pow(d, e) "
                  "+ x.pow(f);")
        self.assertEqual(
            sfg_driver.patch_kernel_source(source),
            "x = std::pow(a, 2.0f) + powf(b, c) + std::pow(d, e) "
            "+ x.pow(f);")

    def test_fabs_is_qualified(self):
        source = "x = fabs(a) + fabsf(b) + std::fabs(c) + x.fabs(d);"
        self.assertEqual(
            sfg_driver.patch_kernel_source(source),
            "x = std::fabs(a) + fabsf(b) + std::fabs(c) + x.fabs(d);")

    def test_simd_rng_key_type(self):
        source = "::pystencils::runtime::x86::random::philox_float64(c, k)"
        self.assertEqual(
            sfg_driver.patch_kernel_source(source),
            "::pystencils::runtime::x86::random::"
            "philox_float64<int64_t>(c, k)")

    def test_patches_are_idempotent(self):
        source = ("auto r = pystencils::runtime::random::philox_float64(x);\n"
                  "auto s = ::pystencils::runtime::random::"
                  "philox_float32(y);\n"
                  "auto k = ::x86::random::philox_float32(a, b);\n"
                  "auto m = sqrt(x) + fmin(a, b) + fmax(a, b) + pow(a, b) "
                  "+ fabs(a) + std::sqrt(x);")
        patched = sfg_driver.patch_kernel_source(source)
        self.assertEqual(sfg_driver.patch_kernel_source(patched), patched)

    def test_member_calls_are_left_alone(self):
        source = "a.sqrt(x) + p->fmin(y, z)"
        self.assertEqual(sfg_driver.patch_kernel_source(source), source)

    def test_generator_patches_sources_only(self):
        tmp = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        ctx = sfg_driver.CodegenContext("double", "cpu")
        with sfg_driver.KernelFileGenerator("Foo", ctx, tmp, "test.py") as sfg:
            sfg.code("inline double foo(double x) { return sqrt(x); }")
            sfg.code("inline double bar(double x) { return sqrt(x); }",
                     impl=True)
        self.assertIn("return sqrt(x);", (tmp / "Foo.h").read_text())
        self.assertIn("return std::sqrt(x);", (tmp / "Foo.cpp").read_text())


