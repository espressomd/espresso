import os
import pathlib
import re
import subprocess
import sys
import tempfile
import unittest

import generate_lb_kernels
import lb_accessors
import pystencils_espresso
import sfg_driver
from tests import header_api

# The API data files were extracted from the FieldAccessors headers generated
# with pystencils 1.4 (Jinja template). They are the API contract of the
# waLBerla bridge, which the generated accessors must fulfill.
DATA_DIR = pathlib.Path(__file__).resolve().parent / "data"
NAMESPACES = ("Population", "Vector", "EquilibriumDistribution",
              "Equilibrium", "Density", "Velocity", "Force",
              "MomentumDensity", "PressureTensor")


def namespace_block(source, name):
    """Text of all blocks of the namespace ``name`` of a header."""
    blocks = re.findall(rf"^\s*namespace {name} \{{.*?^\s*\}} // namespace "
                        rf"{name}$", source, re.S | re.M)
    assert blocks, name
    return "\n".join(blocks)


def without_kernels(block):
    """A namespace block without its nested namespaces ``cpu_kernels``."""
    return re.sub(r"^\s*namespace cpu_kernels \{.*?^\s*\} "
                  r"// namespace cpu_kernels$", "", block, flags=re.S | re.M)


def remove_directory(path):
    for item in path.iterdir():
        item.unlink()
    path.rmdir()


def generate_headers():
    tmp = pathlib.Path(tempfile.mkdtemp())
    for precision in ("double", "single"):
        ctx = sfg_driver.CodegenContext(precision, "cpu")
        fields = pystencils_espresso.generate_fields(
            generate_lb_kernels.STENCIL, ctx.data_type)
        method = generate_lb_kernels.create_lb_method(fields)
        with sfg_driver.KernelFileGenerator(
                ctx.class_name("FieldAccessors"), ctx, tmp,
                "generate_lb_kernels.py", header_only=True) as sfg:
            lb_accessors.generate_field_accessors(sfg, ctx, method)
    return tmp


class FieldAccessorsTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.tmp = generate_headers()
        cls.headers = {
            p: (cls.tmp / f"FieldAccessors{p}Precision.h").read_text()
            for p in ("Double", "Single")}

    @classmethod
    def tearDownClass(cls):
        remove_directory(cls.tmp)

    def test_only_headers_are_generated(self):
        self.assertEqual(sorted(p.name for p in self.tmp.iterdir()),
                         ["FieldAccessorsDoublePrecision.h",
                          "FieldAccessorsSinglePrecision.h"])

    def test_metadata(self):
        for header in self.headers.values():
            self.assertIn(
                "Generated by maintainer/walberla_kernels/"
                "generate_lb_kernels.py", header)
            self.assertIn("#include <vector>", header)
            self.assertIn("#include \"stencil/D3Q19.h\"", header)

    def test_namespaces(self):
        for header in self.headers.values():
            for name in NAMESPACES:
                self.assertRegex(
                    header, rf"namespace {name}\s*{{", name)
            self.assertIn("namespace walberla", header)

    def test_namespaces_of_functions(self):
        for header in self.headers.values():
            namespaces = {f[0] for f in header_api.functions(header)}
            self.assertEqual(
                namespaces, {f"lbm::accessor::{n}" for n in NAMESPACES})

    def test_single_precision_has_no_double(self):
        self.assertNotIn("double", self.headers["Single"])
        self.assertIn("float", self.headers["Single"])

    def test_double_precision_has_no_float(self):
        self.assertIsNone(re.search(r"\bfloat\b|\d\.\d*f\b",
                                    self.headers["Double"]))

    def test_functions_and_kernels_are_inline(self):
        # the header is self-contained: the pystencils kernels are defined
        # in it, and no function can be defined in two translation units
        for header in self.headers.values():
            functions = header_api.functions(header, include_kernels=True)
            self.assertEqual(len(re.findall(r"^\s*inline ", header, re.M)),
                             len(functions))
            kernels = [f for f in functions if f[0].endswith("::cpu_kernels")]
            # sizes of the LB catalogue: 18 kernels, 30 API functions
            self.assertEqual(len(kernels), 18)
            self.assertEqual(len(functions) - len(kernels), 30)
            self.assertNotIn("namespace {", header)
            self.assertNotIn("__global__", header)

    def test_kernels_are_not_part_of_the_api(self):
        for header in self.headers.values():
            self.assertTrue(all(
                not f[0].endswith("::cpu_kernels")
                for f in header_api.functions(header)))
            self.assertGreater(len(header_api.functions(
                header, include_kernels=True)), 30)  # API functions

    def test_kernel_sources_need_no_patch(self):
        # sfg_driver.patch_kernel_source patches the generated .cpp and .cu
        # files, but not the headers: the accessor kernels don't use what it
        # replaces (the pystencils runtime namespace, sqrt, fmin, fmax)
        for header in self.headers.values():
            self.assertEqual(sfg_driver.patch_kernel_source(header), header)
            self.assertNotIn("pystencils::runtime::", header)

    def test_header_does_not_include_the_pystencils_runtime(self):
        # it includes x86 intrinsics, which clang can't compile in a CUDA
        # translation unit that includes the accessors
        for header in self.headers.values():
            self.assertNotIn("pystencils_runtime/generic_cpu.hpp", header)

    def test_no_cuda_or_device_buffers(self):
        for header in self.headers.values():
            for word in ("thrust", "atomic", "gpu::", "device"):
                self.assertNotIn(word, header)

    def test_cell_accessors_do_not_allocate(self):
        # the accessors of single cells are called for every cell of
        # a loop in Python: the values are exchanged through the stack
        cell_function = re.compile(
            r"^\s*inline [^{]*?\bCell\s*&\s*cell\)\s*\{(.*?)^\s*\}",
            re.S | re.M)
        for header in self.headers.values():
            n_functions = 0
            for namespace in ("Population", "Vector", "Density", "Velocity",
                              "Force", "PressureTensor", "Equilibrium"):
                block = without_kernels(namespace_block(header, namespace))
                for function in cell_function.findall(block):
                    n_functions += 1
                    self.assertNotIn("std::vector", function)
                    self.assertNotIn("new ", function)
            # number of single-cell functions of the LB catalogue
            self.assertEqual(n_functions, 13)

    def test_reductions_use_the_reduction_kernels(self):
        # the kernel adds the values of the cells to the accumulators of the
        # function, in the order of the cells, without a buffer of the
        # values of all cells
        for precision, header in self.headers.items():
            fp = "double" if precision == "Double" else "float"
            for name, n in (("MomentumDensity", 3), ("PressureTensor", 9)):
                block = namespace_block(header, name)
                kernels = block[:block.rindex("} // namespace cpu_kernels")]
                self.assertEqual(
                    {int(i) for i in re.findall(
                        rf"{fp}\s*\*\s*const\s+sum_(\d+)", kernels)},
                    set(range(n)))
                function = re.search(
                    r"^\s*inline\s+auto\s+reduce\(.*?^\s*\}",
                    without_kernels(block), re.S | re.M).group(0)
                self.assertEqual(len(re.findall(
                    rf"{fp}\s+acc_\d+\{{0\}};", function)), n)
                self.assertEqual(len(re.findall(
                    rf"{fp}\s*\*\s*const\s+sum_\d+\s*=\s*&acc_\d+;",
                    function)), n)
                self.assertEqual(function.count("::cpu_kernels::"), 1)
                for word in ("std::vector", "buffer_ptr", "emplace",
                             "out", "thrust"):
                    self.assertNotIn(word, function, (name, word))

    def test_api_equals_frozen_contract(self):
        for precision, header in self.headers.items():
            reference = header_api.load_records(
                DATA_DIR / f"field_accessors_api_{precision.lower()}.json")
            expected = header_api.counters(reference)
            actual = header_api.signature_counters(header)
            # number of API functions of the LB catalogue
            self.assertEqual(sum(expected["return type"].values()), 30)
            for label, counter in expected.items():
                self.assertEqual(
                    actual[label], counter,
                    f"{precision} precision, {label}: "
                    f"missing {counter - actual[label]}, "
                    f"unexpected {actual[label] - counter}")

    def test_generation_is_deterministic(self):
        # independent of the hash seed of the interpreter
        kernels_dir = pathlib.Path(__file__).resolve().parent.parent
        script = ("from tests.test_field_accessors import "
                  "generate_headers; print(generate_headers())")
        outputs = []
        for seed in ("1", "2"):
            env = dict(os.environ, PYTHONHASHSEED=seed)
            result = subprocess.run(
                [sys.executable, "-c", script], cwd=kernels_dir, env=env,
                capture_output=True, text=True, check=True)
            path = pathlib.Path(result.stdout.strip().splitlines()[-1])
            self.addCleanup(remove_directory, path)
            outputs.append(path)
        names = sorted(p.name for p in outputs[0].iterdir())
        self.assertEqual(names, sorted(p.name for p in outputs[1].iterdir()))
        self.assertEqual(len(names), 2)
        for name in names:
            self.assertEqual((outputs[0] / name).read_bytes(),
                             (outputs[1] / name).read_bytes(), name)


class HeaderApiTest(unittest.TestCase):

    HEADER = """
    namespace walberla { namespace lbm { namespace accessor {
    namespace Density {
    // inline int ignored();
    inline auto get(const field::GhostLayerField<double, 19u> * pdf_field,
                    const double density, Cell const & cell) {
        for (int i = 0; i < 2; ++i) { }
        return 0.0;
    }
    inline void set(Vector3<double> const &u = Vector3<double>(0.0)) {}
    }}}}
    """

    def test_functions(self):
        self.assertEqual(header_api.functions(self.HEADER), [
            ("lbm::accessor::Density", "get",
             (("GhostLayerField<double,19> const*", "pdf_field", None),
              ("double", "density", None),
              ("Cell const&", "cell", None)), "auto"),
            ("lbm::accessor::Density", "set",
             (("Vector3<double> const&", "u", "Vector3<double>(0.0)"),),
             "void")])

    def test_differences_are_detected(self):
        counters = header_api.signature_counters(self.HEADER)
        for old, new in (("const double density", "const float density"),
                         ("pdf_field,", "field,"),
                         ("inline auto get", "inline void get"),
                         ("(0.0)", "(1.0)")):
            changed = header_api.signature_counters(
                self.HEADER.replace(old, new))
            self.assertNotEqual(changed, counters, (old, new))

    def test_records_roundtrip(self):
        funcs = header_api.functions(self.HEADER)
        records = header_api.to_records(funcs)
        self.assertEqual(
            sorted(header_api.from_records(records)), sorted(funcs))

    def test_kernels_are_ignored_unless_requested(self):
        header = """
        namespace walberla { namespace lbm { namespace accessor {
        namespace Density {
        namespace cpu_kernels {
        inline void get(double *RESTRICT const _data_buf1, int64_t n) {}
        } // namespace cpu_kernels
        inline double get(double density) { return density; }
        }}}}
        """
        self.assertEqual(
            [(f[0], f[1]) for f in header_api.functions(header)],
            [("lbm::accessor::Density", "get")])
        self.assertEqual(
            [f[0] for f in header_api.functions(
                header, include_kernels=True)],
            ["lbm::accessor::Density::cpu_kernels", "lbm::accessor::Density"])

    def test_by_value_const_is_ignored(self):
        counters = header_api.signature_counters(self.HEADER)
        changed = header_api.signature_counters(
            self.HEADER.replace("const double density", "double density"))
        self.assertEqual(changed, counters)


class HeaderApiDeclarationsTest(unittest.TestCase):

    HEADER = """
    #pragma once
    #define RESTRICT __restrict__
    namespace walberla::lbm::accessor {
    namespace Density {
    // double ignored(int);
    double get(gpu::GPUField<double> const *pdf_field, double density,
               Cell const &cell);
    std::vector<double>
    get(gpu::GPUField<double> const *pdf_field, double density,
        CellInterval const &ci);
    void set(Vector3<double> const &u = Vector3<double>(0.0));
    using T = double;
    inline void defined(int) {}
    }}
    """

    def test_declarations(self):
        self.assertEqual(
            header_api.functions(self.HEADER, declarations=True), [
                ("lbm::accessor::Density", "get",
                 (("gpu::GPUField<double> const*", "pdf_field", None),
                  ("double", "density", None),
                  ("Cell const&", "cell", None)), "double"),
                ("lbm::accessor::Density", "get",
                 (("gpu::GPUField<double> const*", "pdf_field", None),
                  ("double", "density", None),
                  ("CellInterval const&", "ci", None)),
                 "std::vector<double>"),
                ("lbm::accessor::Density", "set",
                 (("Vector3<double> const&", "u", "Vector3<double>(0.0)"),),
                 "void")])

    def test_inline_mode_ignores_declarations(self):
        self.assertEqual(
            [f[1] for f in header_api.functions(self.HEADER)], ["defined"])

    def test_differences_are_detected(self):
        counters = header_api.signature_counters(
            self.HEADER, declarations=True)
        for old, new in (("double density", "float density"),
                         ("pdf_field", "field"),
                         ("std::vector<double>\n", "void\n")):
            changed = header_api.signature_counters(
                self.HEADER.replace(old, new), declarations=True)
            self.assertNotEqual(changed, counters, (old, new))


if __name__ == "__main__":
    unittest.main()
