"""
Tests of the field accessors of the electrokinetics
(``walberla::ek::accessor``): the API that the waLBerla bridge relies on, the
structure of the generated files of both targets and both precisions, and
their symbols, which must not clash with the ones of the other kernels
because the CPU and CUDA files and the LB accessors are linked into one
library.
"""

import os
import pathlib
import re
import subprocess
import sys
import tempfile
import unittest

import pystencils as ps

import ek_accessors
import generate_ek_kernels
import sfg_driver
from tests import header_api
from tests import test_field_accessors
from tests import test_field_accessors_cuda
from tests.test_accessor_symbols import definitions

# The API data files were extracted from the headers that the old Jinja
# template of pystencils 1.4 generated. They are the API contract of the
# waLBerla bridge, which the generated accessors must fulfill, with two
# differences. The scalar of the functions that set a value was passed
# as ``double const&`` in the old CPU header and is passed by value (the
# calls are the same). The name of the parameter of ``Scalar::get`` for a
# cell interval in the old CUDA header was ``ield``, which is ``field`` now.
DATA_DIR = pathlib.Path(__file__).resolve().parent / "data"
NAMESPACES = ("Scalar", "Vector", "Flux")
PRECISIONS = (("Double", "double"), ("Single", "float"))
KERNELS = pathlib.Path(__file__).resolve().parents[1]


def generate_files():
    """
    Generate the accessors of both precisions and both targets: the headers
    ``EKFieldAccessors<P>Precision.h`` for the CPU and the files
    ``EKFieldAccessors<P>PrecisionCUDA.{cuh,cu}`` for CUDA.
    """
    tmp = pathlib.Path(tempfile.mkdtemp())
    for precision in ("double", "single"):
        for target, extension in (("cpu", "h"), ("cuda", "cuh")):
            ctx = sfg_driver.CodegenContext(precision, target)
            with sfg_driver.KernelFileGenerator(
                    ctx.class_name("EKFieldAccessors"), ctx, tmp,
                    "generate_ek_kernels.py", header_only=target == "cpu",
                    header_extension=extension) as sfg:
                ek_accessors.generate_field_accessors(sfg, ctx)
    return tmp


class EkAccessorsTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.tmp = generate_files()
        cls.cpu = {p: (cls.tmp / f"EKFieldAccessors{p}Precision.h"
                       ).read_text() for p, _ in PRECISIONS}
        cls.cuda = {p: (cls.tmp / f"EKFieldAccessors{p}PrecisionCUDA.cuh"
                        ).read_text() for p, _ in PRECISIONS}
        cls.cuda_source = {p: (cls.tmp / f"EKFieldAccessors{p}PrecisionCUDA.cu"
                               ).read_text() for p, _ in PRECISIONS}

    @classmethod
    def tearDownClass(cls):
        test_field_accessors.remove_directory(cls.tmp)

    def test_files(self):
        self.assertEqual(sorted(p.name for p in self.tmp.iterdir()), sorted(
            f"EKFieldAccessors{p}Precision{s}"
            for p in ("Double", "Single")
            for s in (".h", "CUDA.cuh", "CUDA.cu")))

    def test_metadata(self):
        for text in (*self.cpu.values(), *self.cuda.values()):
            self.assertIn("Generated by maintainer/walberla_kernels/"
                          "generate_ek_kernels.py", text)
            self.assertIn("Electrokinetics field accessors.", text)
            self.assertIn("namespace walberla::ek::accessor", text)

    def test_namespaces_of_functions(self):
        for text in self.cpu.values():
            namespaces = {f[0] for f in header_api.functions(text)}
            self.assertEqual(
                namespaces, {f"ek::accessor::{n}" for n in NAMESPACES})
        for text in self.cuda.values():
            namespaces = {f[0] for f in header_api.functions(
                text, declarations=True)}
            self.assertEqual(
                namespaces, {f"ek::accessor::{n}" for n in NAMESPACES})

    def test_cpu_api_equals_frozen_contract(self):
        for precision, _ in PRECISIONS:
            reference = header_api.load_records(
                DATA_DIR / f"ek_field_accessors_api_{precision.lower()}.json")
            expected = header_api.counters(reference)
            actual = header_api.signature_counters(self.cpu[precision])
            # number of API functions of the EK catalogue
            self.assertEqual(sum(expected["return type"].values()), 19)
            for label, counter in expected.items():
                self.assertEqual(
                    actual[label], counter,
                    f"{precision} precision, {label}: "
                    f"missing {counter - actual[label]}, "
                    f"unexpected {actual[label] - counter}")

    def test_cuda_api_equals_frozen_contract(self):
        for precision, _ in PRECISIONS:
            reference = header_api.load_records(
                DATA_DIR
                / f"ek_field_accessors_cuda_api_{precision.lower()}.json")
            expected = header_api.counters(reference)
            actual = header_api.signature_counters(
                self.cuda[precision], declarations=True)
            self.assertEqual(sum(expected["return type"].values()), 19)
            for label, counter in expected.items():
                self.assertEqual(
                    actual[label], counter,
                    f"{precision} precision, {label}: "
                    f"missing {counter - actual[label]}, "
                    f"unexpected {actual[label] - counter}")

    def test_the_flux_field_has_13_components(self):
        for precision, c_type in PRECISIONS:
            functions = header_api.functions(self.cpu[precision])
            flux = [f for f in functions if f[0] == "ek::accessor::Flux"]
            self.assertEqual(len(flux), 5)
            fields = {f[2][0][0] for f in flux}
            self.assertEqual(fields, {f"GhostLayerField<{c_type},13> const*",
                                      f"GhostLayerField<{c_type},13>*"})

    def test_flux_get_of_an_interval_has_all_components(self):
        # the old accessors returned the first three components of each cell
        for precision, _ in PRECISIONS:
            block = test_field_accessors.without_kernels(
                test_field_accessors.namespace_block(
                    self.cpu[precision], "Flux"))
            function = re.search(
                r"inline auto get\([^)]*CellInterval& ci\)\s*\{(.*?)^\s*\}",
                block, re.S | re.M).group(1)
            self.assertIn("out(ci.numCells() * 13u)", function)
            self.assertIn("_stride_buf13_2 { int64_t( 13 ) }", function)
            self.assertIn("_stride_buf13_3 { int64_t( 1 ) }", function)

    def test_single_precision_has_no_double(self):
        self.assertNotIn("double", self.cpu["Single"])
        self.assertNotIn("double", self.cuda["Single"])
        self.assertIn("float", self.cpu["Single"])

    def test_double_precision_has_no_float(self):
        for text in (self.cpu["Double"], self.cuda["Double"],
                     self.cuda_source["Double"]):
            self.assertIsNone(re.search(r"\bfloat\b|\d\.\d*f\b", text))

    def test_cpu_functions_and_kernels_are_inline(self):
        # the header is self-contained: the pystencils kernels are defined
        # in it, and no function can be defined in two translation units
        for header in self.cpu.values():
            functions = header_api.functions(header, include_kernels=True)
            self.assertEqual(len(re.findall(r"^\s*inline ", header, re.M)),
                             len(functions))
            kernels = [f for f in functions if f[0].endswith("::cpu_kernels")]
            # sizes of the EK catalogue: 13 kernels, 19 API functions
            self.assertEqual(len(kernels), 13)
            self.assertEqual(len(functions) - len(kernels), 19)
            self.assertNotIn("namespace {", header)
            self.assertNotIn("__global__", header)

    def test_cpu_header_needs_no_patch(self):
        # sfg_driver.patch_kernel_source patches the generated .cpp and .cu
        # files, but not the headers
        for header in self.cpu.values():
            self.assertEqual(sfg_driver.patch_kernel_source(header), header)
            self.assertNotIn("pystencils_runtime/generic_cpu.hpp", header)

    def test_no_cuda_in_the_cpu_header(self):
        for header in self.cpu.values():
            for word in ("thrust", "atomic", "gpu::", "device"):
                self.assertNotIn(word, header)

    def test_cell_accessors_do_not_allocate(self):
        # the accessors of single cells are called for every cell of a loop
        # in Python: the values are exchanged through the stack
        cell_function = re.compile(
            r"^\s*inline [^{]*?\bCell\s*&\s*cell\)\s*\{(.*?)^\s*\}",
            re.S | re.M)
        for header in self.cpu.values():
            n_functions = 0
            for namespace in NAMESPACES:
                block = test_field_accessors.without_kernels(
                    test_field_accessors.namespace_block(header, namespace))
                for function in cell_function.findall(block):
                    n_functions += 1
                    self.assertNotIn("std::vector", function)
                    self.assertNotIn("new ", function)
            # get, set, add of a scalar and a vector, get and get_vector of
            # the flux
            self.assertEqual(n_functions, 8)

    def test_flux_vector_reads_the_neighbors(self):
        # half the sum over the 26 faces, 13 of them in the flux of the
        # neighbors (the cell holds the faces in the positive directions)
        for header in self.cpu.values():
            block = test_field_accessors.without_kernels(
                test_field_accessors.namespace_block(header, "Flux"))
            function = re.search(
                r"inline auto get_vector\([^)]*Cell& cell\)\s*\{(.*?)^"
                r"\s*\}", block, re.S | re.M).group(1)
            self.assertEqual(function.count("::cpu_kernels::"), 1)
        for text in self.cuda_source.values():
            self.assertIn("get_vector", text)

    def test_cuda_source(self):
        for text in self.cuda_source.values():
            self.assertIn("__global__", text)
            self.assertIn("namespace walberla::ek::accessor", text)

    def test_generation_is_deterministic(self):
        # independent of the hash seed of the interpreter
        script = ("from tests.test_ek_accessors import generate_files; "
                  "print(generate_files())")
        outputs = []
        for seed in ("1", "2"):
            env = dict(os.environ, PYTHONHASHSEED=seed)
            result = subprocess.run(
                [sys.executable, "-c", script], cwd=KERNELS, env=env,
                capture_output=True, text=True, check=True)
            path = pathlib.Path(result.stdout.strip().splitlines()[-1])
            self.addCleanup(test_field_accessors.remove_directory, path)
            outputs.append(path)
        names = sorted(p.name for p in outputs[0].iterdir())
        self.assertEqual(names, sorted(p.name for p in outputs[1].iterdir()))
        self.assertEqual(len(names), 6)
        for name in names:
            self.assertEqual((outputs[0] / name).read_bytes(),
                             (outputs[1] / name).read_bytes(), name)


class EkAccessorsRegistryTest(unittest.TestCase):

    def test_registered_kernels(self):
        kernels = generate_ek_kernels.KERNELS
        cpu = kernels["field_accessors"]
        cuda = kernels["field_accessors_cuda"]
        for kernel, targets, extension in ((cpu, ("cpu",), "h"),
                                           (cuda, ("cuda",), "cuh")):
            self.assertIsInstance(kernel, sfg_driver.Kernel)
            self.assertEqual(kernel.stem, "EKFieldAccessors")
            self.assertEqual(kernel.targets, targets)
            self.assertEqual(kernel.header_extension, extension)
        self.assertTrue(cpu.header_only)
        self.assertFalse(cuda.header_only)

    def test_catalogue(self):
        for dtype in ("float32", "float64"):
            catalogue = ek_accessors.EkAccessors(
                ps.create_type(dtype)).catalogue()
            self.assertEqual(catalogue.namespace, "walberla::ek::accessor")
            self.assertEqual([ns.name for ns in catalogue.namespaces],
                             list(NAMESPACES))
            self.assertEqual(len(catalogue.accessors("cpu")), 19)
            self.assertEqual(len(catalogue.accessors("cuda")), 19)
            self.assertEqual(
                {f.fsize for f in catalogue.fields.values()}, {1, 3, 13})


class EkAccessorSymbolsTest(unittest.TestCase):
    """
    The functions of the CPU and of the CUDA accessors and the functions of
    the LB accessors (which are in the same library) must not have the same
    qualified name and parameter types: the linker would bind them to each
    other without a diagnostic.
    """

    @classmethod
    def setUpClass(cls):
        cls.tmp = generate_files()
        cls.lb_cpu_dir = test_field_accessors.generate_headers()
        cls.lb_cuda_dir = test_field_accessors_cuda.generate_files()

    @classmethod
    def tearDownClass(cls):
        for directory in (cls.tmp, cls.lb_cpu_dir, cls.lb_cuda_dir):
            test_field_accessors.remove_directory(directory)

    def read(self, name):
        return definitions((self.tmp / name).read_text())

    def test_cpu_and_cuda_functions_are_disjoint(self):
        for p, _ in PRECISIONS:
            cpu = self.read(f"EKFieldAccessors{p}Precision.h")
            cuda = self.read(f"EKFieldAccessors{p}PrecisionCUDA.cu")
            self.assertEqual(
                {n for n, _ in cpu if "kernels::" in n and
                 "cpu_kernels" not in n}, set())
            self.assertTrue(any("::cpu_kernels::" in n for n, _ in cpu))
            self.assertTrue(any("::kernels::" in n for n, _ in cuda))
            self.assertEqual(cpu & cuda, set(),
                             f"{p} precision: shared functions")

    def test_ek_and_lb_functions_are_disjoint(self):
        for p, _ in PRECISIONS:
            ek = (self.read(f"EKFieldAccessors{p}Precision.h")
                  | self.read(f"EKFieldAccessors{p}PrecisionCUDA.cu"))
            lb_cpu = self.lb_cpu_dir / f"FieldAccessors{p}Precision.h"
            lb_cuda = self.lb_cuda_dir / f"FieldAccessors{p}PrecisionCUDA.cu"
            lb = (definitions(lb_cpu.read_text())
                  | definitions(lb_cuda.read_text()))
            self.assertTrue(ek and lb)
            self.assertEqual(ek & lb, set())
            self.assertEqual({n.split("::")[1] for n, _ in ek}, {"ek"})
            self.assertEqual({n.split("::")[1] for n, _ in lb}, {"lbm"})

    def test_precisions_are_in_the_same_library(self):
        # the single and the double precision functions differ in the
        # parameter types, so they are different symbols
        double = self.read("EKFieldAccessorsDoublePrecision.h")
        single = self.read("EKFieldAccessorsSinglePrecision.h")
        self.assertEqual(double & single, set())


if __name__ == "__main__":
    unittest.main()
