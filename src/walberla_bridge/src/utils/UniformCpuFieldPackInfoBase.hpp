#pragma once

/**
 * @file
 * @ref walberla::UniformCpuFieldPackInfoBase is the base class of the CPU pack
 * infos generated by <tt>maintainer/walberla_kernels/pack_infos.py</tt>.
 * It is the CPU counterpart of
 * <tt>walberla::sweepgen::UniformGpuFieldPackInfoBase</tt>, which the
 * generated CUDA pack infos derive from.
 */

#include <communication/UniformPackInfo.h>
#include <core/DataTypes.h>
#include <core/cell/CellInterval.h>
#include <core/mpi/RecvBuffer.h>
#include <core/mpi/SendBuffer.h>
#include <domain_decomposition/BlockDataID.h>
#include <domain_decomposition/IBlock.h>
#include <stencil/Directions.h>

#include <cstddef>
#include <memory>
#include <span>

namespace walberla {

/**
 * @brief Pack info of a ghost layer field, for use with
 * @c walberla::blockforest::communication::UniformBufferedScheme.
 *
 * The communicated field components of each direction are not specified
 * here: the derived class @c Impl provides them, together with the kernels
 * that copy them between the field and a linear buffer. It must define
 * - the type @c Field_T, a @c walberla::field::GhostLayerField,
 * - <tt>void doPack(Field_T *field, std::span<value_type> buffer,
 *   Direction dir, CellInterval const &interval) const</tt> that copies the
 *   components of @c dir in @c interval of @c field to @c buffer,
 * - <tt>void doUnpack(Field_T *field, std::span<value_type> buffer,
 *   Direction dir, CellInterval const &interval) const</tt> that copies the
 *   components of @c dir from @c buffer to @c interval of @c field,
 * - <tt>void doLocalCopy(Field_T *src, CellInterval const &src_interval,
 *   Field_T *dst, CellInterval const &dst_interval, Direction dir)
 *   const</tt> that
 *   copies the components of @c dir directly between two fields, and
 * - <tt>uint_t elementsPerCell(Direction dir) const</tt>, the number of
 *   components of @c dir (zero for directions that are not communicated).
 *
 * The direction passed to @c doUnpack is the direction of the sender, i.e.
 * the inverse of the direction of the ghost layer that is filled.
 * The buffer holds @c elementsPerCell(dir) values per cell of the interval.
 *
 * This class has the interface of the pack infos that were generated with
 * @c pystencils_walberla (constructor, @c pack, @c unpack, @c size and
 * @c communicateLocal), so that the bridge doesn't depend on how they
 * are generated.
 *
 * @tparam Impl Derived class (CRTP)
 */
template <typename Impl>
class UniformCpuFieldPackInfoBase
    : public ::walberla::communication::UniformPackInfo {
public:
  /**
   * @param fieldId ID of the field in the block storage
   * @param sliceWidth Number of ghost layers to communicate
   */
  explicit UniformCpuFieldPackInfoBase(BlockDataID fieldId,
                                       uint_t sliceWidth = 1u)
      : fieldId_{fieldId}, sliceWidth_{cell_idx_c(sliceWidth)} {}
  ~UniformCpuFieldPackInfoBase() override = default;

  bool constantDataExchange() const override { return true; }
  bool threadsafeReceiving() const override { return true; }

  void unpackData(IBlock *receiver, stencil::Direction dir,
                  mpi::RecvBuffer &buffer) override {
    using value_type = typename Impl::Field_T::value_type;
    auto const dataSize = size(dir, receiver);
    auto bufferSize = dataSize + sizeof(value_type);
    auto bufferPtr = reinterpret_cast<void *>(buffer.skip(bufferSize));
    std::align(alignof(value_type), dataSize, bufferPtr, bufferSize);
    unpack(dir, reinterpret_cast<unsigned char *>(bufferPtr), receiver);
  }

  /** Copy the slice of the sender next to the ghost layer of @c dir directly
   * to the ghost layer of the receiver, without a buffer.
   */
  void communicateLocal(IBlock const *sender, IBlock *receiver,
                        stencil::Direction dir) override {
    using Field_T = typename Impl::Field_T;
    auto *const src_field =
        const_cast<IBlock *>(sender)->getData<Field_T>(fieldId_);
    auto *const dst_field = receiver->getData<Field_T>(fieldId_);
    CellInterval src_interval;
    CellInterval dst_interval;
    src_field->getSliceBeforeGhostLayer(dir, src_interval, sliceWidth_, false);
    dst_field->getGhostRegion(stencil::inverseDir[dir], dst_interval,
                              sliceWidth_, false);
    impl().doLocalCopy(src_field, src_interval, dst_field, dst_interval, dir);
  }

  /** Pack the slice of the block next to the ghost layer of @c dir. */
  void pack(stencil::Direction dir, unsigned char *rawBuffer,
            IBlock *block) const {
    using Field_T = typename Impl::Field_T;
    using value_type = typename Field_T::value_type;
    auto *const field = block->getData<Field_T>(fieldId_);
    CellInterval interval;
    field->getSliceBeforeGhostLayer(dir, interval, sliceWidth_, false);
    std::span<value_type> const buffer{
        reinterpret_cast<value_type *>(rawBuffer),
        impl().elementsPerCell(dir) * interval.numCells()};
    impl().doPack(field, buffer, dir, interval);
  }

  /** Unpack into the ghost layer of @c dir of the block. */
  void unpack(stencil::Direction dir, unsigned char *rawBuffer,
              IBlock *block) const {
    using Field_T = typename Impl::Field_T;
    using value_type = typename Field_T::value_type;
    auto *const field = block->getData<Field_T>(fieldId_);
    CellInterval interval;
    field->getGhostRegion(dir, interval, sliceWidth_, false);
    std::span<value_type> const buffer{
        reinterpret_cast<value_type *>(rawBuffer),
        impl().elementsPerCell(dir) * interval.numCells()};
    impl().doUnpack(field, buffer, stencil::inverseDir[dir], interval);
  }

  /** Size in bytes of the data exchanged in direction @c dir. */
  uint_t size(stencil::Direction dir, IBlock const *block) const {
    using Field_T = typename Impl::Field_T;
    using value_type = typename Field_T::value_type;
    auto const *const field = block->getData<Field_T>(fieldId_);
    CellInterval interval;
    field->getGhostRegion(dir, interval, sliceWidth_, false);
    return impl().elementsPerCell(dir) * interval.numCells() *
           sizeof(value_type);
  }

protected:
  void packDataImpl(IBlock const *sender, stencil::Direction dir,
                    mpi::SendBuffer &outBuffer) const override {
    using value_type = typename Impl::Field_T::value_type;
    auto const dataSize = size(dir, sender);
    auto bufferSize = dataSize + sizeof(value_type);
    auto bufferPtr = reinterpret_cast<void *>(outBuffer.forward(bufferSize));
    std::align(alignof(value_type), dataSize, bufferPtr, bufferSize);
    pack(dir, reinterpret_cast<unsigned char *>(bufferPtr),
         const_cast<IBlock *>(sender));
  }

  BlockDataID fieldId_;
  cell_idx_t sliceWidth_;

private:
  Impl const &impl() const { return static_cast<Impl const &>(*this); }
};

} // namespace walberla
