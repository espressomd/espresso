#pragma once

/**
 * @file
 * @ref walberla::IndexVectorBoundary is the base class of the boundary
 * conditions that are applied to the links between cells and boundary
 * cells, such as the @c DynamicUBB class of the lattice Boltzmann method and
 * the @c Dirichlet class of the electrokinetics, which are generated by
 * <tt>maintainer/walberla_kernels/boundaries.py</tt>. It replaces the code
 * that the Jinja template <tt>Boundary.tmpl.h</tt> of the former code
 * generator emitted into every boundary header. The generated class only
 * provides the kernel that processes a list of links; this header collects
 * the links from the flag field, stores them on the host and on the device,
 * and runs the kernel.
 *
 * Links and force vectors
 * -----------------------
 * A link is an element of an index vector: a cell and the direction
 * of the stencil that points to a boundary cell, and the boundary data of the
 * link (the first four members of the @c IndexInfo struct are the
 * coordinates @c x, @c y, @c z and the direction @c dir, all @c int32_t).
 * Which cells have links is defined by the link policy (see below); the
 * description of the vectors is the one of the lattice Boltzmann boundaries,
 * the default policy @ref walberla::FluidLinks.
 * Each block stores three index vectors, which are filled by
 * @ref walberla::IndexVectorBoundary::fillFromFlagField :
 * - @c ALL: all links of the block, ordered by direction first (in the order
 *   of the stencil), then by the order of the cells in memory;
 * - @c INNER: the links of the cells that are at least one cell away from the
 *   boundary of the block (cells of the interval @c xyzSize() shrunk by one);
 * - @c OUTER: the other links (in the layer of cells next to the block
 *   boundary and in the first ghost layer).
 *
 * @c INNER and @c OUTER are the links of @c ALL that fulfill the condition,
 * in the same relative order. The kernel can run on any of the three vectors
 * (@c run, @c inner and @c outer) to overlap the processing of the
 * @c INNER links with the communication of the ghost layers. Since a fluid
 * cell is never a boundary cell, the links of @ref walberla::FluidLinks
 * don't depend on each other and the order of the links in a vector doesn't
 * matter for the result. The links of the other policies may share a cell
 * (one link for each direction), so their kernels must not read what another
 * link writes. For the same reason, kernels must not write the same element
 * from two links unless both write the same value (write/write overlap, e.g.
 * the flux of the fixed flux boundary through a face that two links share).
 *
 * Link policies
 * -------------
 * The template argument @c LinkPolicy selects the cells that are searched for
 * links and the cells that the links point to. The policy is a struct with
 * three @c static @c constexpr members:
 * - @c fluid_cells_only: a link starts only in a cell without the boundary
 *   flag;
 * - @c skip_center: there is no link in the direction @c stencil::C;
 * - @c ghost_margin: the cells that are searched are the interior of the
 *   block and all ghost layers except for the outermost @c ghost_margin
 *   layers. With @c ghost_margin = 1, the cells that a link points to are
 *   always inside the field; with 0, all ghost layers are searched, which
 *   requires a stencil that has no other direction than @c stencil::C
 *   (checked at compile time).
 *
 * A link is a cell of the searched region that has the domain flag, that
 * fulfills @c fluid_cells_only, and whose neighbor in the direction of the
 * link has the boundary flag. The value callback is called with the
 * neighbor, i.e. the boundary cell, for each link. The policies are:
 * - @ref walberla::FluidLinks (the default): the cells are the fluid cells,
 *   the links have all the directions of the stencil. This is the policy of
 *   the lattice Boltzmann boundaries.
 * - @ref walberla::DomainLinksNoCenter takes all domain cells, boundary cells
 *   included, and all directions but @c stencil::C. This is the policy of the
 *   fixed flux boundary of the electrokinetics, which stores a flux for
 *   each face between a cell and a boundary neighbor.
 * - @ref walberla::DomainLinksWithGhostLayers with
 *   @ref walberla::CellStencil takes the boundary cells themselves, in the
 *   interior and in all ghost layers (the link of a cell points to the cell
 *   itself). This is the policy of the Dirichlet boundary of the
 *   electrokinetics, which stores a value in each boundary cell.
 *
 * The last two policies are those of the former generated classes of the
 * electrokinetics. The former fixed flux class also had a link of each
 * boundary cell to itself (direction @c stencil::C), which its kernel
 * ignored.
 *
 * Forces
 * ------
 * The kernel of a lattice Boltzmann boundary writes the force that acts on
 * the boundary through each link to a struct (a @c ForceStruct with the
 * members @c F_0, @c F_1 and @c F_2). A boundary without force (the
 * electrokinetics boundaries) passes @c void as @c ForceStruct: it has no
 * force vectors, its kernel doesn't take a force vector argument, and
 * @c getForce, @c getForceVector and @c getForceVectorID do not exist
 * (@ref walberla::IndexVectorBoundary::has_force is @c false).
 *
 * Each block of a boundary with force has one force vector for each type of
 * index vector; a force vector has the same length and order as its index
 * vector, and a kernel that runs on an index vector writes the force vector
 * of the same type only. In particular, @c run() doesn't change the forces
 * of @c INNER and @c OUTER, and vice versa. The total force of a sweep is the
 * sum of the force vector of its type: after @c run() it is
 * <tt>getForce(block)</tt> (= <tt>getForce(block, ALL)</tt>), after
 * @c inner() and @c outer() it is the sum of
 * <tt>getForce(block, INNER)</tt> and <tt>getForce(block, OUTER)</tt>.
 * All forces are reset to zero by @c fillFromFlagField.
 * The old generated class had a single force vector of the length of
 * @c ALL, which @c inner() and @c outer() overwrote from the first element on
 * (CPU) or read past the end of (GPU).
 *
 * On the device, the force vectors are written in device memory, and the
 * host vectors (@c getForceVector, @c ForceVector::forceVector) are stale
 * until @c ForceVector::syncCPU(type) was called for the type in question
 * (every type, not only @c ALL); @c getForce(block, type) does it itself.
 *
 * The bridge only uses the @c ALL vectors: @c getIndexVector(block) and
 * @c getForceVector(block) return them, and so does @c getForce(block) for the
 * total force.
 *
 * Interface of the derived class
 * ------------------------------
 * The derived class @c Impl of the CRTP base must define
 * - the type @c PdfField_T, the field the kernel works on
 *   (a @c walberla::field::GhostLayerField on the host, a
 *   @c walberla::gpu::GPUField on the device),
 * - <tt>static void assignValue(IndexInfo &element, Value const &value)</tt>
 *   that stores the value of the value callback in the boundary data of a
 *   link,
 * - <tt>void linkKernel(PdfField_T *pdfs, IndexInfo *indexVector,
 *   ForceStruct *forceVector, std::size_t size)</tt> on the host, with an
 *   additional argument <tt>gpuStream_t stream</tt> on the device, which
 *   processes the @c size links of the two arrays (on the device, they are
 *   arrays in device memory). It must @b overwrite the force of each link
 *   (not accumulate it): @c run() leaves the forces of the other types
 *   untouched, and @c getForce sums the force vector of one type. Without
 *   force, the kernel has no @c forceVector argument,
 * - <tt>static constexpr neighborOffset</tt>, the array of the stencil
 *   offsets (<tt>std::array<std::array<int, Q>, D></tt>, indexed by the
 *   dimension and the direction), which the bridge uses as
 *   <tt>Kernels::DynamicUBB::neighborOffset</tt>.
 *
 * The device version needs a waLBerla with CUDA or HIP support
 * (<tt>WALBERLA_BUILD_WITH_CUDA</tt>). The header contains no kernel and no
 * non-template function: the CPU and CUDA boundary classes instantiate
 * different templates (@ref walberla::IndexVectorMemory is a template
 * argument) and never define the same function, which matters because both are
 * linked into one library in builds with CUDA.
 */

